// makeL(lang) gives L(key, vars): the string in that language, else in English, else the key itself, its {name}
// placeholders filled from vars; and Lp(key, n, vars): the { one, other } form for n, {n} filled (French counts 0 and 1 as one).
function makeL(lang) {
  var own = Object.prototype.hasOwnProperty, code = own.call(CHROME_TEXT, lang) ? lang : 'en';
  function pick(key) {
    if (own.call(CHROME_TEXT[code], key)) return CHROME_TEXT[code][key];
    return own.call(CHROME_TEXT.en, key) ? CHROME_TEXT.en[key] : key;
  }
  function fill(s, vars) {
    return String(s).replace(/\{(\w+)\}/g, function (m, name) { return vars && own.call(vars, name) ? String(vars[name]) : m; });
  }
  function L(key, vars) { return fill(pick(key), vars); }
  function Lp(key, n, vars) {
    var v = pick(key), one = code === 'fr' ? Math.abs(n) < 2 : n === 1, all = { n: n };
    if (vars) Object.keys(vars).forEach(function (k) { all[k] = vars[k]; });
    return fill(v && typeof v === 'object' ? (one ? v.one : v.other) : v, all);
  }
  return { L: L, Lp: Lp };
}
